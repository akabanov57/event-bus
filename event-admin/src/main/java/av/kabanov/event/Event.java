package av.kabanov.event;

/**
 * Маркерный интерфейс для всех событий в системе.
 * <p>
 * Любой класс или рекорд (Record), представляющий собой событие, должен реализовывать
 * данный интерфейс и предоставлять структурированное имя топика.
 * </p>
 * Пример реализации:
 * <pre>
 * public record OrderCreated(long id, double price) implements Event {
 *     @Override
 *     public String topic() {
 *         return "app/orders/created";
 *     }
 * }
 * </pre>
 */
public interface Event {
    /**
     * Возвращает уникальный идентификатор топика (канала) события.
     * Рекомендуется использовать иерархическую структуру разделения через слэш (например, "модуль/сущность/действие").
     *
     * @return строковое представление топика, не должно быть пустой строкой или null.
     */
    String topic();

    // По умолчанию пустая строка (для событий, где порядок не важен)
    default String routingKey() {
        return "";
    }
}
