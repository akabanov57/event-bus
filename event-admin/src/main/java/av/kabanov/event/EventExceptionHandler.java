package av.kabanov.event;

/**
 * Функциональный интерфейс для централизованного перехвата и обработки исключений, возникающих в
 * процессе выполнения кода подписчиков.
 * <p>
 * Позволяет полностью изолировать ошибки бизнес-логики от ядра инфраструктуры шины событий,
 * предотвращая падение потоков-обработчиков и обеспечивая бесперебойную доставку событий.
 * </p>
 */
@FunctionalInterface
public interface EventExceptionHandler {

  /**
   * Метод обратного вызова, срабатывающий при возникновении любой ошибки в подписчике.
   *
   * @param event        Событие, в момент обработки которого произошло исключение.
   * @param throwable    Выброшенное исключение или ошибка (Throwable).
   * @param listenerName Идентификатор или имя класса подписчика для детального логирования и
   *                     трассировки.
   */
  void handle(Event event, Throwable throwable, String listenerName);
}
