package av.kabanov.event;

/**
 * Токен управления жизненным циклом подписки.
 * Позволяет безопасно отменить подписку на события без необходимости обработки проверяемых исключений.
 */
public interface Subscriber extends AutoCloseable {

  /**
   * Отменяет текущую подписку и гарантированно удаляет обработчик из ядра шины событий.
   * Не выбрасывает никаких проверяемых исключений.
   */
  @Override
  void close();
}
